/**
 * Assumption lab: change the big VNCMA drivers and re-run a Monte Carlo of a model portfolio.
 * Runs in the browser; the visitor's scenario is never stored or published.
 *
 * Expected returns move by the *deltas* of the VNCMA building blocks (core/cma/blocks.py), applied to the approved
 * release values, so the baseline is exactly the published release. Every block is linear in the drivers:
 *   cash      = pi + r_star                         -> +dPi + dReal
 *   gov       = y0 + D (y0 - y_eq) / h, y_eq = pi + r_star_gov + tp
 *                                                   -> -D (dPi + dReal) / h
 *   corp      = gov + spread - loss                 -> same as gov
 *   equities  = D/P + pi + g*haircut - dilution + 100 ln(PE_T/PE_0)/h
 *                                                   -> +dPi + haircut dG + 100 ln(1 + dPE)/h
 *   gold, usd = ... + d, d = pi - pi_us             -> +dPi
 * Equity volatility can be scaled and the equity-bond correlation overridden (kept positive definite).
 */

import { rng } from "./goals.ts";

export const LAB_CLASSES = ["cash_vnd", "gov_bond", "corp_bond", "eq_large", "eq_midsmall", "gold", "usd"] as const;
const EQUITY = new Set(["eq_large", "eq_midsmall"]);
const BONDS = new Set(["gov_bond", "corp_bond"]);

export type LabClass = { id: string; ret: number; vol: number };
export type LabBase = {
  classes: LabClass[]; // in LAB_CLASSES order
  corr: number[][];
  horizon: number; // years in the VNCMA formulas
  duration: number; // modified duration of the 10-year government bond
  haircut: number; // share of GDP growth reaching earnings per share
  inflation: number;
};

export type Shocks = {
  inflation: number; // pp
  growth: number; // pp, real GDP
  real: number; // pp, real interest rate
  pe: number; // fraction, end-of-horizon P/E vs expected (-0.3 = 30% lower)
  volScale: number; // multiplier on equity volatility
  stockBond: number | null; // correlation override between equities and bonds
  crash: boolean; // equities fall 40% in the first year
};

export const NO_SHOCK: Shocks = { inflation: 0, growth: 0, real: 0, pe: 0, volScale: 1, stockBond: null, crash: false };

/** Pull the numbers the deltas need from the approved release (formula strings are generated by our own code). */
export function labBase(v: {
  horizon_years: number;
  classes: { id: string; expected_return: string; volatility: string | null; formula: string }[];
  correlation: { classes: string[]; matrix: number[][] };
  macro: Record<string, { value: string }>;
}): LabBase | null {
  const by = new Map(v.classes.map((c) => [c.id, c]));
  const classes: LabClass[] = [];
  for (const id of LAB_CLASSES) {
    const c = by.get(id);
    if (!c || c.volatility == null) return null;
    classes.push({ id, ret: Number(c.expected_return), vol: Number(c.volatility) });
  }
  const idx = LAB_CLASSES.map((id) => v.correlation.classes.indexOf(id));
  if (idx.some((i) => i < 0)) return null;
  const corr = idx.map((i) => idx.map((j) => v.correlation.matrix[i][j]));
  const duration = Number(/\bD ([\d.]+)/.exec(by.get("gov_bond")?.formula ?? "")?.[1] ?? 8);
  const haircut = Number(/\bg [\d.]+ x ([\d.]+)/.exec(by.get("eq_large")?.formula ?? "")?.[1] ?? 0.6);
  return { classes, corr, horizon: v.horizon_years || 10, duration, haircut, inflation: Number(v.macro.pi?.value ?? 4) };
}

/** Expected geometric return of each class under the shocks (percent a year). */
export function scenarioReturns(base: LabBase, s: Shocks): number[] {
  const bond = (-base.duration * (s.inflation + s.real)) / base.horizon;
  const valuation = (100 * Math.log(1 + s.pe)) / base.horizon;
  return base.classes.map((c) => {
    if (c.id === "cash_vnd") return c.ret + s.inflation + s.real;
    if (BONDS.has(c.id)) return c.ret + bond;
    if (EQUITY.has(c.id)) return c.ret + s.inflation + base.haircut * s.growth + valuation;
    return c.ret + s.inflation; // gold and usd move with VND depreciation
  });
}

export function scenarioVols(base: LabBase, s: Shocks): number[] {
  return base.classes.map((c) => (EQUITY.has(c.id) ? c.vol * s.volScale : c.vol));
}

/** Lower-triangular Cholesky factor, or null if the matrix is not positive definite. */
export function cholesky(a: number[][]): number[][] | null {
  const n = a.length;
  const l = a.map(() => Array(n).fill(0) as number[]);
  for (let i = 0; i < n; i++) {
    for (let j = 0; j <= i; j++) {
      let sum = a[i][j];
      for (let k = 0; k < j; k++) sum -= l[i][k] * l[j][k];
      if (i === j) {
        if (sum <= 1e-10) return null;
        l[i][i] = Math.sqrt(sum);
      } else l[i][j] = sum / l[j][j];
    }
  }
  return l;
}

/** Correlation with the equity-bond pairs overridden; shrunk towards the identity until positive definite. */
export function scenarioCorr(base: LabBase, s: Shocks): { corr: number[][]; chol: number[][]; shrunk: number } {
  const ids = base.classes.map((c) => c.id);
  const target = base.corr.map((row, i) =>
    row.map((v, j) => {
      if (i === j || s.stockBond === null) return v;
      const pair = (EQUITY.has(ids[i]) && BONDS.has(ids[j])) || (BONDS.has(ids[i]) && EQUITY.has(ids[j]));
      return pair ? s.stockBond : v;
    }),
  );
  for (let k = 0; k <= 20; k++) {
    const lambda = k / 20;
    const m = target.map((row, i) => row.map((v, j) => (i === j ? 1 : (1 - lambda) * v)));
    const chol = cholesky(m);
    if (chol) return { corr: m, chol, shrunk: lambda };
  }
  const id = ids.map((_, i) => ids.map((__, j) => (i === j ? 1 : 0)));
  return { corr: id, chol: id, shrunk: 1 };
}

export type SimInput = {
  weights: number[]; // fractions in LAB_CLASSES order, sum 1
  initial: number; // VND today
  monthly: number; // VND a month in today's money
  years: number;
  paths: number;
  seed: number;
};

export type SimResult = {
  /** Value in today's money (deflated by the scenario inflation) at the end of each year: [path][year 0..years]. */
  values: Float64Array[];
  finals: number[]; // sorted
  /** The portfolio's own nominal return in each simulated year (percent), all paths and years together. */
  yearReturns: Float64Array;
};

/**
 * Monthly simulation: correlated normal log returns per class (mean ln(1+E)/12, sd sigma/sqrt 12), rebalanced to
 * the weights every month; contributions rise with inflation; values are reported in today's money. The same seed
 * gives the same random draws, so baseline and scenario differ only by their assumptions.
 */
export function simulate(input: SimInput, rets: number[], vols: number[], chol: number[][], inflation: number, crash: boolean): SimResult {
  const n = rets.length;
  const months = Math.round(input.years * 12);
  const mu = rets.map((r) => Math.log(1 + r / 100) / 12);
  const sd = vols.map((v) => v / 100 / Math.sqrt(12));
  const piM = Math.pow(1 + inflation / 100, 1 / 12);
  const random = rng(input.seed);
  const gauss = () => {
    let u = 0;
    while (u === 0) u = random();
    return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * random());
  };
  const z = new Float64Array(n);
  const values: Float64Array[] = [];
  const yearReturns = new Float64Array(input.paths * input.years);
  for (let p = 0; p < input.paths; p++) {
    let v = input.initial;
    let deflator = 1;
    const yearly = new Float64Array(input.years + 1);
    yearly[0] = v;
    let yearGrowth = 1;
    for (let m = 1; m <= months; m++) {
      for (let i = 0; i < n; i++) z[i] = gauss();
      let growth = 0;
      for (let i = 0; i < n; i++) {
        let e = 0;
        for (let k = 0; k <= i; k++) e += chol[i][k] * z[k];
        let factor = Math.exp(mu[i] + sd[i] * e);
        if (crash && m === 6 && EQUITY.has(LAB_CLASSES[i])) factor *= 0.6;
        growth += input.weights[i] * factor;
      }
      deflator *= piM;
      yearGrowth *= growth;
      v = v * growth + input.monthly * deflator;
      if (m % 12 === 0) {
        yearly[m / 12] = v / deflator;
        yearReturns[p * input.years + m / 12 - 1] = 100 * (yearGrowth - 1);
        yearGrowth = 1;
      }
    }
    values.push(yearly);
  }
  const finals = values.map((y) => y[input.years]).sort((a, b) => a - b);
  return { values, finals, yearReturns };
}

export function percentile(sorted: ArrayLike<number>, q: number): number {
  if (sorted.length === 0) return NaN;
  const pos = (sorted.length - 1) * q;
  const lo = Math.floor(pos);
  const hi = Math.ceil(pos);
  return sorted[lo] + (sorted[hi] - sorted[lo]) * (pos - lo);
}

/** Per year: the 10/25/50/75/90th percentiles of value. */
export function bands(sim: SimResult, years: number): { p10: number; p25: number; p50: number; p75: number; p90: number }[] {
  return Array.from({ length: years + 1 }, (_, y) => {
    const col = sim.values.map((v) => v[y]).sort((a, b) => a - b);
    return { p10: percentile(col, 0.1), p25: percentile(col, 0.25), p50: percentile(col, 0.5), p75: percentile(col, 0.75), p90: percentile(col, 0.9) };
  });
}

/** 100 quantiles of the final value (a quantile dot plot: each dot is one in a hundred futures). */
export function hundred(finals: number[]): number[] {
  return Array.from({ length: 100 }, (_, i) => percentile(finals, (i + 0.5) / 100));
}

export const chance = (finals: number[], goal: number) => finals.filter((v) => v >= goal).length / Math.max(1, finals.length);

/** Counts of `values` in equal bins over [lo, hi] (values outside go to the end bins). */
export function histogram(values: ArrayLike<number>, bins: number, lo: number, hi: number): number[] {
  const out = Array(bins).fill(0) as number[];
  const w = (hi - lo) / bins || 1;
  for (let i = 0; i < values.length; i++) out[Math.max(0, Math.min(bins - 1, Math.floor((values[i] - lo) / w)))]++;
  return out;
}

/** Average of the equity-bond correlations in the release (the slider's starting point). */
export function baseStockBond(base: LabBase): number {
  const ids = base.classes.map((c) => c.id);
  const vals: number[] = [];
  ids.forEach((a, i) => ids.forEach((b, j) => EQUITY.has(a) && BONDS.has(b) && vals.push(base.corr[i][j])));
  return vals.length ? vals.reduce((x, y) => x + y, 0) / vals.length : 0;
}

export type Sensitivity = { id: string; low: number | null; high: number; lowShock: Shocks | null; highShock: Shocks };

/** Chance of the goal when each driver moves one step down and up from the current scenario. */
export function sensitivity(base: LabBase, current: Shocks, plan: SimInput, goal: number): { now: number; rows: Sensitivity[] } {
  const run = (s: Shocks) => {
    const corr = scenarioCorr(base, s);
    return chance(simulate(plan, scenarioReturns(base, s), scenarioVols(base, s), corr.chol, base.inflation + s.inflation, s.crash).finals, goal);
  };
  const sb = current.stockBond ?? baseStockBond(base);
  const clamp = (v: number, lo: number, hi: number) => Math.max(lo, Math.min(hi, v));
  const steps: [string, Partial<Shocks>, Partial<Shocks>][] = [
    ["inflation", { inflation: current.inflation - 1 }, { inflation: current.inflation + 1 }],
    ["growth", { growth: current.growth - 1 }, { growth: current.growth + 1 }],
    ["real", { real: current.real - 0.5 }, { real: current.real + 0.5 }],
    ["pe", { pe: Math.max(-0.9, current.pe - 0.15) }, { pe: current.pe + 0.15 }],
    ["vol", { volScale: current.volScale * 0.8 }, { volScale: current.volScale * 1.25 }],
    ["stockBond", { stockBond: clamp(sb - 0.3, -0.9, 0.9) }, { stockBond: clamp(sb + 0.3, -0.9, 0.9) }],
  ];
  const rows: Sensitivity[] = steps.map(([id, lo, hi]) => {
    const lowShock = { ...current, ...lo };
    const highShock = { ...current, ...hi };
    return { id, low: run(lowShock), high: run(highShock), lowShock, highShock };
  });
  if (!current.crash) {
    const crash = { ...current, crash: true };
    rows.push({ id: "crash", low: null, high: run(crash), lowShock: null, highShock: crash });
  }
  const now = run(current);
  const swing = (r: Sensitivity) => Math.max(Math.abs((r.low ?? now) - now), Math.abs(r.high - now));
  return { now, rows: rows.sort((a, b) => swing(b) - swing(a)) };
}

/** Liquid holdings from the balance sheet, as lab weights (percent). Bonds count as government bonds, shares as VN30. */
export function weightsFromAssets(assets: { kind: string; value: number }[]): Record<string, number> | null {
  const map: Record<string, string> = { deposit: "cash_vnd", bond: "gov_bond", stock: "eq_large", gold: "gold", usd: "usd" };
  const sums: Record<string, number> = {};
  for (const a of assets) {
    const c = map[a.kind];
    if (c && a.value > 0) sums[c] = (sums[c] ?? 0) + a.value;
  }
  const total = Object.values(sums).reduce((x, y) => x + y, 0);
  if (total <= 0) return null;
  return Object.fromEntries(Object.entries(sums).map(([k, v]) => [k, (100 * v) / total]));
}
